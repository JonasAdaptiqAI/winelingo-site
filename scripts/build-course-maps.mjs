// Builds assets/course/maps.js for the web course from the app's Course 2.0 map data
// (prototype/lib/maps.ts + lib/places.ts, generated there from Natural Earth and places.json),
// so a map card in the browser draws the same outline and pins as the iPhone app. Run after the
// app's maps or places change:
//
//   node scripts/build-course-maps.mjs [path/to/winelingo-app/prototype/lib]
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { homedir } from "node:os";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = process.argv[2] ?? join(homedir(), "dev/winelingo-app/prototype/lib");

function constOf(file, name) {
  const src = readFileSync(join(SRC, file), "utf8");
  const m = src.match(new RegExp(`export const ${name}[^=]*=\\s*([\\s\\S]*?\\n?\\});?\\s*(\\n|$)`));
  if (!m) throw new Error(`${name} not found in ${file}`);
  return vm.runInNewContext(`(${m[1]})`);
}
const MAPS = constOf("maps.ts", "MAPS");
const PLACES = constOf("places.ts", "PLACES");
const out = `/* Generated by scripts/build-course-maps.mjs from the app's lib/maps.ts and lib/places.ts
   (Natural Earth, public domain) — do not edit. Country outlines and wine-place pins for the
   lesson map cards. */
window.WL_MAPS = ${JSON.stringify(MAPS)};
window.WL_PLACES = ${JSON.stringify(PLACES)};
`;
writeFileSync(join(ROOT, "assets/course/maps.js"), out);
console.log(`maps.js: ${Object.keys(MAPS).length} maps, ${Object.keys(PLACES).length} places, ${(out.length / 1024).toFixed(0)} KB`);
